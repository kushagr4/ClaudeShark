"""Evaluation tests.

The fast evaluator packs middlegame and endgame scores into one integer and
unrolls its bitboard scans. Both are the kind of optimisation that can be
subtly wrong on a rare board -- a sign-extension edge, a mis-copied table -- so
the central test here is equivalence against the transparently correct
reference implementation over a wide spread of positions, including ones
generated by actually playing moves rather than only hand-picked FENs.
"""

from __future__ import annotations

import random

import chess
import pytest

from cs_constants import TOTAL_PHASE
from cs_eval import evaluate, evaluate_reference, is_material_draw
from tools.positions import BALANCED_OPENINGS, SHARP_POSITIONS

EXTREMES = (
    "4k3/8/8/8/8/8/8/4K3 w - - 0 1",  # bare kings
    "QQQQkQQQ/QQQ5/8/8/8/8/8/4K3 w - - 0 1",  # phase overflow
    "qqqqKqqq/qqq5/8/8/8/8/8/4k3 b - - 0 1",  # the same, mirrored
    "8/PPPPPPPP/8/4k3/4K3/8/pppppppp/8 w - - 0 1",  # pawns about to promote
    "rnbqkbnr/pppppppp/8/8/8/8/PPPPPPPP/RNBQKBNR w KQkq - 0 1",
    "3k4/8/8/8/8/8/8/3QK3 w - - 0 1",  # lopsided
    "8/8/8/3k4/3K4/8/8/8 w - - 0 1",
)


def _random_positions(count: int, seed: int = 20260902) -> list[chess.Board]:
    """Positions reached by random legal play, to escape hand-picked bias."""
    rng = random.Random(seed)
    boards: list[chess.Board] = []
    while len(boards) < count:
        board = chess.Board()
        for _ in range(rng.randint(0, 80)):
            moves = list(board.legal_moves)
            if not moves:
                break
            board.push(rng.choice(moves))
        boards.append(board.copy(stack=False))
    return boards


ALL_FENS = tuple(BALANCED_OPENINGS) + tuple(SHARP_POSITIONS) + EXTREMES


@pytest.mark.parametrize("fen", ALL_FENS)
def test_fast_evaluator_matches_the_reference(fen: str) -> None:
    board = chess.Board(fen)
    assert evaluate(board) == evaluate_reference(board), fen


def test_fast_evaluator_matches_the_reference_on_random_play() -> None:
    mismatches = []
    for board in _random_positions(400):
        if evaluate(board) != evaluate_reference(board):
            mismatches.append(board.fen())
    assert not mismatches, f"{len(mismatches)} mismatches, first: {mismatches[:3]}"


def test_packing_survives_a_lopsided_endgame_total() -> None:
    """The endgame half must not overflow its 16 bits on an extreme board."""
    board = chess.Board("QQQQkQQQ/QQQ5/8/8/8/8/8/4K3 w - - 0 1")
    assert evaluate(board) == evaluate_reference(board)
    assert evaluate(board) > 0


@pytest.mark.parametrize("fen", ALL_FENS)
def test_evaluation_is_symmetric_under_colour_flip(fen: str) -> None:
    board = chess.Board(fen)
    assert evaluate(board) == evaluate(board.mirror()), fen


def test_evaluation_prefers_more_material() -> None:
    even = chess.Board("4k3/8/8/8/8/8/8/4K3 w - - 0 1")
    up_a_rook = chess.Board("4k3/8/8/8/8/8/8/R3K3 w - - 0 1")
    assert evaluate(up_a_rook) > evaluate(even) + 400


def test_phase_never_exceeds_the_total() -> None:
    board = chess.Board("QQQQkQQQ/QQQ5/8/8/8/8/8/4K3 w - - 0 1")
    phase = (
        (board.knights | board.bishops).bit_count()
        + 2 * board.rooks.bit_count()
        + 4 * board.queens.bit_count()
    )
    assert phase > TOTAL_PHASE
    evaluate(board)  # must not raise or produce a nonsense taper


def test_material_draw_agrees_with_the_rule() -> None:
    """Spot check; the exhaustive version lives in tests/test_material_draw.py.

    This deliberately asserts agreement with python-chess rather than a
    hand-written expectation. The version it replaces hard-coded K+B vs K+N as
    a draw, which is drawish but not dead, and so encoded the very defect this
    session fixed.
    """
    for fen in (
        "4k3/8/8/8/8/8/8/4K3 w - - 0 1",
        "4k3/8/8/8/8/8/8/3BK3 w - - 0 1",
        "4k1n1/8/8/8/8/8/8/3BK3 w - - 0 1",
        "4k3/8/8/8/8/8/4P3/4K3 w - - 0 1",
        "4k3/8/8/8/8/8/8/3RK3 w - - 0 1",
        "4k3/8/8/8/8/8/8/2BBK3 w - - 0 1",
    ):
        board = chess.Board(fen)
        assert is_material_draw(board) == board.is_insufficient_material(), fen
